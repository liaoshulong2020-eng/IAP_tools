/**
 * notch_filter.h
 * 母线 100Hz 工频纹波陷波滤波器
 * Fs=10kHz, Fnotch=100Hz, BW=10Hz
 * 单精度浮点版本
 */

#ifndef NOTCH_FILTER_H
#define NOTCH_FILTER_H

/* ================================================================
 * 只需修改这里（MATLAB 系数直接粘贴，末尾加 f）
 * ================================================================ */
#define NOTCH_B0  ( 0.998403955733781378611979562265332788229f)
#define NOTCH_B1  (-1.992867667181661417430404981132596731186f)
#define NOTCH_B2  ( 0.998403955733781378611979562265332788229f)
#define NOTCH_A1  (-1.992867667181661417430404981132596731186f)
#define NOTCH_A2  ( 0.996807911467562757223959124530665576458f)
/* ================================================================ */


/* 滤波器状态结构体 */
typedef struct {
    float w1, w2;
} NotchState;


/* ----------------------------------------------------------------
 * 函数声明
 * ---------------------------------------------------------------- */

/**
 * notch_init - 初始化滤波器状态（上电调用一次）
 * @s: 滤波器状态指针
 */
void notch_init(volatile NotchState *s);

/**
 * notch_tick - 处理单个样点（在 10kHz 中断中调用）
 * @s: 滤波器状态指针
 * @x: 输入样点（原始母线电压）
 * 返回: 滤波后的电压值
 */
float notch_tick(volatile NotchState *s, float x);

/**
 * notch_reset - 重置滤波器状态（保留系数，清零延迟）
 * @s: 滤波器状态指针
 */
void notch_reset(volatile NotchState *s);


#endif /* NOTCH_FILTER_H */